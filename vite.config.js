import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { defineConfig } from 'vite';
import { VitePWA } from 'vite-plugin-pwa';

const projectRoot = fileURLToPath(new URL('.', import.meta.url));

export default defineConfig(({ mode }) => {
  const isDesktop = mode === 'desktop';

  return {
    // GitHub Pages serves this project from /OGCruncher/; Neutralino desktop serves from root.
    base: isDesktop ? './' : '/OGCruncher/',
    build: {
      outDir: 'dist',
      assetsDir: 'assets',
      // Ensure we have hashes in filenames for cache busting
      rollupOptions: {
        // Five real pages: English at /OGCruncher/ plus /uk/, /pl/, /ru/, /ko/
        // (generated by scripts/build-locales.cjs).
        input: {
          main: resolve(projectRoot, 'index.html'),
          uk: resolve(projectRoot, 'uk/index.html'),
          pl: resolve(projectRoot, 'pl/index.html'),
          ru: resolve(projectRoot, 'ru/index.html'),
          ko: resolve(projectRoot, 'ko/index.html'),
        },
        output: {
          entryFileNames: 'assets/[name]-[hash].js',
          chunkFileNames: 'assets/[name]-[hash].js',
          assetFileNames: 'assets/[name]-[hash].[ext]',
        },
      },
    },
    plugins: isDesktop
      ? []
      : [
          VitePWA({
            // Registration is owned by js/main.js and update activation by js/sw-update.js.
            // Prompt-style updates avoid replacing a page that owns in-memory queue files
            // and output Blob URLs.
            registerType: 'prompt',
            injectRegister: null,
            includeAssets: ['robots.txt'],
            manifest: {
              name: 'OGCruncher',
              short_name: 'OGCruncher',
              description: 'A local browser audio bit-crusher and lo-fi converter by Ihor Sivochka.',
              start_url: './index.html',
              display: 'standalone',
              orientation: 'any',
              categories: ['utilities', 'music', 'productivity'],
              theme_color: '#f2f0eb',
              background_color: '#f2f0eb',
              icons: [
                {
                  src: 'images/icon-192.png',
                  sizes: '192x192',
                  type: 'image/png',
                  purpose: 'any',
                },
                {
                  src: 'images/icon-512.png',
                  sizes: '512x512',
                  type: 'image/png',
                  purpose: 'any maskable',
                },
                {
                  src: 'images/logo.svg',
                  sizes: '512x512',
                  type: 'image/svg+xml',
                  purpose: 'any',
                },
              ],
            },
            workbox: {
              skipWaiting: false,
              clientsClaim: false,
              // Cache all static assets from the build (excluding social share card and icons already emitted from manifest.icons)
              globPatterns: ['**/*.{js,css,html,ico,png,svg,mp3,mem}'],
              globIgnores: ['**/social-card.png', 'images/icon-192.png', 'images/icon-512.png', 'images/logo.svg'],
              // Increase the size limit for cached files (OggVorbisEncoder is ~350kb, .mem is ~550kb)
              maximumFileSizeToCacheInBytes: 5000000,
              // The SPA-style fallback would answer every navigation with the English
              // index.html; localized pages are served from their own precache entries.
              navigateFallbackDenylist: [/\/(?:uk|pl|ru|ko)(\/|$)/],
              runtimeCaching: [],
            },
          }),
        ],
  };
});
